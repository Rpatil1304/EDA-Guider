def display_visualization_recommendations(result):
    """
    Display LLM-validated visualization recommendations.
    """

    st.header("Visualization Recommendations")

    validation = result.get(
        "visualization_validation"
    ) or {}

    validations = validation.get(
        "validations",
        [],
    )

    if not validations:

        st.info(
            "No visualization recommendations were generated."
        )

        return

    for index, recommendation in enumerate(
        validations,
        start=1,
    ):

        if not isinstance(
            recommendation,
            dict,
        ):
            continue

        decision = recommendation.get(
            "decision",
            "accepted",
        )

        chart_type = (
            recommendation.get(
                "final_chart_type"
            )
            or recommendation.get(
                "original_chart_type"
            )
        )

        columns = (
            recommendation.get(
                "final_columns"
            )
            or recommendation.get(
                "original_columns"
            )
        )

        reason = recommendation.get(
            "reason",
            "No explanation provided.",
        )

        confidence = recommendation.get(
            "confidence",
            0,
        )

        chart_name = _format_chart_name(
            chart_type
        )

        with st.container(
            border=True
        ):

            col1, col2 = st.columns(
                [4, 1]
            )

            with col1:

                st.subheader(
                    f"{index}. {chart_name}"
                )

                if columns:

                    st.write(
                        "**Columns:** "
                        + ", ".join(columns)
                    )

                st.write(
                    f"**Why:** {reason}"
                )

            with col2:

                st.metric(
                    "Confidence",
                    f"{confidence * 100:.0f}%"
                )

                if decision == "accepted":

                    st.success(
                        "Accepted"
                    )

                elif decision == "modified":

                    st.warning(
                        "Modified"
                    )

                elif decision == "rejected":

                    st.error(
                        "Rejected"
                    )


