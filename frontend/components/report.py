def _format_number(value):
    """
    Format numeric values for display.
    """

    if value is None:
        return "-"

    if isinstance(
        value,
        (int, float),
    ):

        if isinstance(
            value,
            float,
        ):

            return f"{value:,.2f}"

        return f"{value:,}"

    return str(value)


def _format_percentage(value):
    """
    Format percentage values.
    """

    if value is None:
        return "-"

    try:

        return f"{float(value):.2f}%"

    except (
        TypeError,
        ValueError,
    ):

        return str(value)


