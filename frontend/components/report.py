def display_preprocessing(result):
    """
    Display preprocessing information in human-readable form.
    """

    st.header("Preprocessing Summary")

    preprocessing = result.get(
        "preprocessing"
    ) or {}

    summary = preprocessing.get(
        "summary",
        {},
    )

    raw_rows = summary.get(
        "raw_row_count",
        0,
    )

    cleaned_rows = summary.get(
        "cleaned_row_count",
        0,
    )

    raw_columns = summary.get(
        "raw_column_count",
        0,
    )

    cleaned_columns = summary.get(
        "cleaned_column_count",
        0,
    )

    changed_columns = summary.get(
        "changed_column_count",
        0,
    )

    col1, col2, col3, col4 = st.columns(4)

    with col1:

        st.metric(
            "Rows Before",
            f"{raw_rows:,}",
        )

    with col2:

        st.metric(
            "Rows After",
            f"{cleaned_rows:,}",
        )

    with col3:

        st.metric(
            "Columns Before",
            f"{raw_columns:,}",
        )

    with col4:

        st.metric(
            "Columns Changed",
            changed_columns,
        )

    st.subheader("Preprocessing Actions")

    execution_log = preprocessing.get(
        "execution_log",
        [],
    )

    if execution_log:

        for step in execution_log:

            if not isinstance(step, dict):
                continue

            action = (
                step.get("action")
                or step.get("operation")
                or step.get("step")
                or "Preprocessing action"
            )

            status = step.get(
                "status",
                "completed",
            )

            message = (
                step.get("message")
                or step.get("description")
                or ""
            )

            if str(status).lower() in {
                "success",
                "completed",
                "complete",
                "executed",
            }:

                st.success(
                    f"✓ {action}"
                    + (
                        f" — {message}"
                        if message
                        else ""
                    )
                )

            else:

                st.info(
                    f"• {action}"
                    + (
                        f" — {message}"
                        if message
                        else ""
                    )
                )

    else:

        st.info(
            "No preprocessing actions were recorded."
        )


