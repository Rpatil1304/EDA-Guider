def _format_number(value):
    """
    Format numeric values for display.
    """

    if value is None:
        return "-"

    if isinstance(
        value,
        (int, float),
    ):

        if isinstance(
            value,
            float,
        ):

            return f"{value:,.2f}"

        return f"{value:,}"

    return str(value)


def _format_percentage(value):
    """
    Format percentage values.
    """

    if value is None:
        return "-"

    try:

        return f"{float(value):.2f}%"

    except (
        TypeError,
        ValueError,
    ):

        return str(value)


def _format_chart_name(chart_type):
    """
    Convert technical chart names into
    human-readable names.
    """

    if not chart_type:
        return "Visualization"

    mapping = {
        "histogram": "Histogram",
        "box_plot": "Box Plot",
        "bar_chart": "Bar Chart",
        "pie_chart": "Pie Chart",
        "pie_donut_chart": "Pie / Donut Chart",
        "scatter_plot": "Scatter Plot",
        "line_chart": "Line Chart",
        "grouped_bar_chart": "Grouped Bar Chart",
        "stacked_bar_chart": "Stacked Bar Chart",
        "100_percent_stacked_bar_chart": (
            "100% Stacked Bar Chart"
        ),
        "heatmap": "Correlation Heatmap",
        "correlation_heatmap": (
            "Correlation Heatmap"
        ),
        "missingness_bar_chart": (
            "Missingness Bar Chart"
        ),
        "missingness_heatmap": (
            "Missingness Heatmap"
        ),
        "violin_plot": "Violin Plot",
        "qq_plot": "Q-Q Plot",
        "pair_plot": "Pair Plot",
    }

    return mapping.get(
        chart_type,
        str(chart_type).replace(
            "_",
            " ",
        ).title(),
    )