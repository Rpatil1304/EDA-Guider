def display_dataset_overview(result):
    """
    Display high-level information about the dataset.
    """

    st.header("Dataset Overview")

    raw_profile = result.get("raw_profile") or {}

    row_count = raw_profile.get("row_count", 0)
    column_count = raw_profile.get("column_count", 0)

    columns = raw_profile.get("columns", [])

    numeric_count = 0
    categorical_count = 0
    datetime_count = 0
    boolean_count = 0

    for column in columns:

        inferred_type = str(
            column.get("inferred_type", "")
        ).lower()

        if inferred_type == "numeric":
            numeric_count += 1

        elif inferred_type == "categorical":
            categorical_count += 1

        elif inferred_type == "datetime":
            datetime_count += 1

        elif inferred_type == "boolean":
            boolean_count += 1

    col1, col2, col3, col4 = st.columns(4)

    with col1:
        st.metric(
            "Rows",
            f"{row_count:,}",
        )

    with col2:
        st.metric(
            "Columns",
            f"{column_count:,}",
        )

    with col3:
        st.metric(
            "Numeric Columns",
            numeric_count,
        )

    with col4:
        st.metric(
            "Categorical Columns",
            categorical_count,
        )

    col5, col6 = st.columns(2)

    with col5:
        st.metric(
            "Datetime Columns",
            datetime_count,
        )

    with col6:
        st.metric(
            "Boolean Columns",
            boolean_count,
        )


