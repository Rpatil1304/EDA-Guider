def display_data_quality(result):
    """
    Display dataset quality information.
    """

    st.header("Data Quality")

    raw_profile = result.get("raw_profile") or {}

    null_summary = raw_profile.get(
        "null_summary",
        {},
    )

    total_missing = 0
    columns_with_missing = []

    if isinstance(null_summary, dict):

        total_missing = null_summary.get(
            "total_missing",
            0,
        )

        columns_with_missing = null_summary.get(
            "columns_with_missing",
            [],
        )

    columns = raw_profile.get(
        "columns",
        [],
    )

    if not columns_with_missing:

        for column in columns:

            missing_count = column.get(
                "missing_count",
                0,
            )

            if missing_count and missing_count > 0:

                columns_with_missing.append(
                    {
                        "column": column.get("name"),
                        "missing_count": missing_count,
                        "missing_percentage": column.get(
                            "missing_percentage",
                            0,
                        ),
                    }
                )

    col1, col2 = st.columns(2)

    with col1:

        st.metric(
            "Total Missing Values",
            f"{total_missing:,}",
        )

    with col2:

        st.metric(
            "Columns With Missing Values",
            len(columns_with_missing),
        )

    if columns_with_missing:

        st.subheader("Missing Value Details")

        rows = []

        for item in columns_with_missing:

            if isinstance(item, dict):

                rows.append(
                    {
                        "Column": item.get(
                            "column",
                            "Unknown",
                        ),
                        "Missing Values": item.get(
                            "missing_count",
                            0,
                        ),
                        "Missing %": (
                            f"{item.get('missing_percentage', 0):.2f}%"
                        ),
                    }
                )

        if rows:

            st.dataframe(
                pd.DataFrame(rows),
                use_container_width=True,
                hide_index=True,
            )

    else:

        st.success(
            "No missing values were detected."
        )


